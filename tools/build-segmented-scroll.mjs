// The ESM package is authoritative; this bundle keeps classic-script site consumers working.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { rolldown } from 'rolldown';

const root = resolve(import.meta.dirname, '..');
const destination = resolve(root, 'site/shared/segmented-scroll/browser.js');
const bundle = await rolldown({ input: resolve(root, 'site/shared/segmented-scroll/index.js') });
try {
  const { output } = await bundle.generate({
    format: 'iife',
    name: 'MDWSegmentedScroll',
    banner: '// Generated by npm run build:segmented-scroll. Edit the ESM sources, not this file.'
  });
  const code = output[0].code;
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== code) {
      throw new Error('Segmented scroll browser bundle is stale. Run npm run build:segmented-scroll.');
    }
    console.log('Segmented scroll browser bundle matches the ESM sources.');
  } else {
    await writeFile(destination, code);
  }
} finally {
  await bundle.close();
}
